bool CMath::solvequad_(float a, float b, float c, float& r0, float& r1) {
    float fourAC = a * c * 4.0f;
    float bb = b * b;

    if (bb <= fourAC) {
        return false;
    }

    float root = sqrt(bb - fourAC);
    float q = (b > 0.0f ? b + root : b - root) * -0.5f;
    float inv = 1.0f / (q * a);
    float x0 = q * (inv * q);
    float x1 = c * (a * inv);

    if (x1 > x0) {
        r0 = x0;
        r1 = x1;
    } else {
        r0 = x1;
        r1 = x0;
    }

    return true;
}

