uint32_t CMath::sqrt_(uint32_t n) {
    uint32_t x;

    if (n <= 0xFF) {
        x = n / 12 + 1;
    } else if (n <= 0xFFFF) {
        x = n / 200 + 21;
    } else {
        x = n / 26743 + 444;
    }

    int32_t delta;

    do {
        uint32_t q = n / x;
        delta = static_cast<int32_t>(x - q) / 2;
        x = static_cast<int32_t>(q + x) / 2;
    } while (delta);

    return x;
}

